#!/usr/bin/env bash
# Publish the current version to Thunderstore with tcli.
#
#   TS_TEAM=<team> TCLI_AUTH_TOKEN=<token> ./build/publish.sh
#   ... --dry-run     build and generate config, but do not upload
#
# The token is a Thunderstore *service account* token: Thunderstore -> your team
# -> Service Accounts -> create. Keep it in the environment; never commit it.
#
# tcli reads the package identity from thunderstore.toml and refuses --file
# alongside the --package-* flags, so that file is GENERATED here from
# thunderstore/manifest.json. manifest.json stays the single source of truth and
# the toml is a gitignored build artefact, so the two cannot drift apart.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DRY_RUN=""
[ "${1:-}" = "--dry-run" ] && DRY_RUN=1

: "${TS_TEAM:?set TS_TEAM to your Thunderstore team name}"
if [ -z "$DRY_RUN" ]; then
    : "${TCLI_AUTH_TOKEN:?set TCLI_AUTH_TOKEN to a Thunderstore service account token}"
fi

echo "==> building and validating the bundle"
"$ROOT/build/package.sh" >/dev/null

VERSION=$(python3 -c "import json;print(json.load(open('$ROOT/thunderstore/manifest.json'))['version_number'])")
ZIP="$ROOT/dist/Earshot-$VERSION.zip"
[ -f "$ZIP" ] || { echo "no bundle at $ZIP" >&2; exit 1; }

echo "==> generating thunderstore.toml from manifest.json"
python3 - "$ROOT" "$TS_TEAM" <<'PY'
import json, sys, os
root, team = sys.argv[1], sys.argv[2]
m = json.load(open(os.path.join(root, "thunderstore/manifest.json")))

deps = "\n".join(
    '%s = "%s"' % (d.rsplit("-", 1)[0], d.rsplit("-", 1)[1]) for d in m["dependencies"]
)

toml = f'''# GENERATED by build/publish.sh from thunderstore/manifest.json — do not edit.
[config]
schemaVersion = "0.0.1"

[package]
namespace = "{team}"
name = "{m['name']}"
versionNumber = "{m['version_number']}"
description = "{m['description']}"
websiteUrl = "{m['website_url']}"
containsNsfwContent = false

[package.dependencies]
{deps}

[build]
icon = "./thunderstore/icon.png"
readme = "./thunderstore/README.md"
outdir = "./dist"

[[build.copy]]
source = "./src/Earshot/bin/Release/net472/Earshot.dll"
target = "plugins/Earshot"

[publish]
repository = "https://thunderstore.io"
communities = [ "valheim", ]

[publish.categories]
valheim = [ "client-side", "utility", "ai-generated", ]
'''
open(os.path.join(root, "thunderstore.toml"), "w").write(toml)
print(f"    {team}-{m['name']} {m['version_number']}")
PY

if [ -n "$DRY_RUN" ]; then
    echo "==> dry run: config written, nothing uploaded"
    echo "    bundle: $ZIP"
    exit 0
fi

echo "==> publishing $ZIP"
echo "    a published version can never be replaced or deleted."
cd "$ROOT"
tcli publish --file "$ZIP" --token "$TCLI_AUTH_TOKEN"
